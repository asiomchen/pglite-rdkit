#!/bin/bash
# Build the RDKit static libraries for wasm32 (step 1 of the extension build).
#
# Runs INSIDE the pglite builder image (emsdk), e.g.:
#   scripts/docker.sh scripts/build-rdkit-libs.sh
#
# Output:
#   build/rdkit-build     CMake build tree
#   build/rdkit-install   installed headers, lib*.a and lib/cmake/rdkit (component "dev")
#   build/boost-stage    static wasm Boost.Serialization and Boost.Iostreams
#   build/boost-cmake    BoostConfig.cmake for headers and those two archives;
#                        pass -DBoost_DIR=<this> to any consumer of the RDKit CMake package
#
# Exceptions: the published pglite.js is linked without JS exception support (its __cxa_throw
# aborts), so ALL C++ in the side module is compiled with native wasm exceptions
# (-fwasm-exceptions, legacy wasm EH encoding = emscripten's default WASM_LEGACY_EXCEPTIONS=1).
# throw/catch then stays entirely inside rdkit.so (libc++abi + libunwind linked statically into
# it). -fwasm-exceptions can't be combined with -sSUPPORT_LONGJMP=emscripten, and RDKit doesn't
# use setjmp/longjmp, so that flag is dropped.
#
# Env: DEBUG=true for a -g Debug build; JOBS=<n> to limit build parallelism.
set -euo pipefail

REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$REPO_ROOT"
# shellcheck source=../UPSTREAM.lock
source ./UPSTREAM.lock

if ! command -v emcc >/dev/null; then
  echo "emcc not found: run this inside the builder image (scripts/docker.sh $0)" >&2
  exit 1
fi

RDKIT_SRC=$REPO_ROOT/upstream/rdkit
BOOST_SRC=$REPO_ROOT/upstream/boost
source "$REPO_ROOT/scripts/features.sh"
BUILD_DIR=$REPO_ROOT/build/rdkit-build$FEATURES_SUFFIX
INSTALL_DIR=$REPO_ROOT/build/rdkit-install$FEATURES_SUFFIX
BOOST_CMAKE_DIR=$REPO_ROOT/build/boost-cmake
BOOST_BUILD_DIR=$REPO_ROOT/build/boost-build
BOOST_STAGE_DIR=$REPO_ROOT/build/boost-stage
ZLIB_PREFIX=${ZLIB_PREFIX:-/install/libs}
JOBS=${JOBS:-$(nproc)}

for f in "$RDKIT_SRC/CMakeLists.txt" "$BOOST_SRC/boost/version.hpp" "$ZLIB_PREFIX/lib/libz.a"; do
  [ -f "$f" ] || { echo "missing $f (run scripts/fetch-upstream.sh?)" >&2; exit 1; }
done

# Don't use PGLITE_CFLAGS here: its -Dexit=pgl_exit style overrides break the C++ std headers.
# Boost and RDKit must agree on the exception ABI used by the cartridge side module.
RDKIT_CFLAGS="-m32 -fpic -fwasm-exceptions"
if [ "${DEBUG:-false}" = true ]; then
  RDKIT_CFLAGS="$RDKIT_CFLAGS -g"
  BUILD_TYPE=Debug
  BOOST_VARIANT=debug
else
  RDKIT_CFLAGS="$RDKIT_CFLAGS -O2"
  BUILD_TYPE=Release
  BOOST_VARIANT=release
fi
echo "RDKIT_CFLAGS=$RDKIT_CFLAGS"

# --- Boost -------------------------------------------------------------------------------
# Extended queries store MolBundle/TautomerQuery values using Boost.Serialization. RDKit's
# serialization option also requires the iostreams component, even with compressed I/O off.
# Bootstrap b2 with the host compiler; only the libraries are cross-compiled to wasm.
(
  cd "$BOOST_SRC"
  ./bootstrap.sh --with-toolset=gcc --without-icu --with-libraries=serialization,iostreams
  ./b2 --ignore-site-config --user-config=/dev/null \
    --build-dir="$BOOST_BUILD_DIR" --stagedir="$BOOST_STAGE_DIR" --layout=system \
    -j"$JOBS" toolset=emscripten variant="$BOOST_VARIANT" link=static threading=single \
    cxxstd=20 exception-handling=on "cxxflags=$RDKIT_CFLAGS" define=BOOST_DISABLE_THREADS \
    -sNO_COMPRESSION=1 --with-serialization --with-iostreams stage
)

# The release tarball has a flattened boost/ header tree. Expose its headers and the staged
# archives without relying on a host Boost installation or Boost's generated package layout.
mkdir -p "$BOOST_CMAKE_DIR"
cat > "$BOOST_CMAKE_DIR/BoostConfigVersion.cmake" <<EOF
set(PACKAGE_VERSION "$BOOST_VERSION")
if(PACKAGE_FIND_VERSION VERSION_GREATER PACKAGE_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_FIND_VERSION STREQUAL PACKAGE_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
EOF
cat > "$BOOST_CMAKE_DIR/BoostConfig.cmake" <<EOF
# Generated by scripts/build-rdkit-libs.sh: wasm Boost $BOOST_VERSION from upstream/boost.
set(Boost_FOUND TRUE)
set(Boost_VERSION "$BOOST_VERSION")
set(Boost_VERSION_STRING "$BOOST_VERSION")
set(Boost_INCLUDE_DIR "$BOOST_SRC")
set(Boost_INCLUDE_DIRS "$BOOST_SRC")
set(Boost_USE_STATIC_LIBS ON)
set(Boost_LIBRARIES "")
if(NOT TARGET Boost::headers)
  add_library(Boost::headers INTERFACE IMPORTED)
  set_target_properties(Boost::headers PROPERTIES INTERFACE_INCLUDE_DIRECTORIES "$BOOST_SRC")
endif()
if(NOT TARGET Boost::boost)
  add_library(Boost::boost INTERFACE IMPORTED)
  set_target_properties(Boost::boost PROPERTIES INTERFACE_LINK_LIBRARIES Boost::headers)
endif()
# Define both archives on every find: RDKit's installed config requests serialization but its
# exported rdkit_base interface can also reference iostreams.
foreach(_lib IN ITEMS serialization iostreams)
  if(NOT TARGET Boost::\${_lib})
    add_library(Boost::\${_lib} STATIC IMPORTED)
    set_target_properties(Boost::\${_lib} PROPERTIES
      IMPORTED_LOCATION "$BOOST_STAGE_DIR/lib/libboost_\${_lib}.a"
      INTERFACE_LINK_LIBRARIES Boost::headers)
  endif()
endforeach()
foreach(_comp IN LISTS Boost_FIND_COMPONENTS)
  if(TARGET Boost::\${_comp})
    set(Boost_\${_comp}_FOUND TRUE)
    list(APPEND Boost_LIBRARIES Boost::\${_comp})
  else()
    set(Boost_\${_comp}_FOUND FALSE)
    if(Boost_FIND_REQUIRED_\${_comp})
      set(Boost_FOUND FALSE)
      set(Boost_NOT_FOUND_MESSAGE "Boost component \${_comp} is not available in the wasm build")
    endif()
  endif()
endforeach()
EOF

# --- RDKit ---------------------------------------------------------------------------------
# Compile flags only: these are static libraries, so link settings (-sWASM_BIGINT etc.) belong to
# build-cartridge.sh, which links them into rdkit.so

emcmake cmake -S "$RDKIT_SRC" -B "$BUILD_DIR" -Wno-dev \
  -DCMAKE_BUILD_TYPE=$BUILD_TYPE \
  -DCMAKE_C_FLAGS="$RDKIT_CFLAGS" \
  -DCMAKE_CXX_FLAGS="$RDKIT_CFLAGS" \
  -DCMAKE_INSTALL_PREFIX="$INSTALL_DIR" \
  -DCMAKE_FIND_ROOT_PATH_MODE_PACKAGE=BOTH \
  -DBoost_DIR="$BOOST_CMAKE_DIR" \
  -DBoost_USE_STATIC_LIBS=ON \
  -DZLIB_INCLUDE_DIR="$ZLIB_PREFIX/include" \
  -DZLIB_LIBRARY="$ZLIB_PREFIX/lib/libz.a" \
  -DRDK_BUILD_PGSQL=OFF \
  -DRDK_INSTALL_INTREE=OFF \
  -DRDK_BUILD_PYTHON_WRAPPERS=OFF \
  -DRDK_BUILD_BOOST_PYTHON_WRAPPERS=OFF \
  -DRDK_BUILD_NANOBIND_WRAPPERS=OFF \
  -DRDK_BUILD_CPP_TESTS=OFF \
  -DRDK_BUILD_THREADSAFE_SSS=OFF \
  -DRDK_TEST_MULTITHREADED=OFF \
  -DRDK_OPTIMIZE_POPCNT=OFF \
  -DRDK_USE_BOOST_SERIALIZATION=ON \
  -DRDK_USE_BOOST_IOSTREAMS=OFF \
  -DRDK_USE_URF=OFF \
  -DRDK_BUILD_FREETYPE_SUPPORT=OFF \
  -DRDK_BUILD_CAIRO_SUPPORT=OFF \
  -DRDK_BUILD_INCHI_SUPPORT=$RDK_INCHI \
  -DINCHI_URL="file://$REPO_ROOT/upstream/downloads/$(basename "$INCHI_URL")" \
  -DINCHI_MD5SUM="$INCHI_MD5" \
  -DRDK_BUILD_AVALON_SUPPORT=$RDK_AVALON \
  -DRDK_BUILD_COORDGEN_SUPPORT=OFF \
  -DRDK_BUILD_MAEPARSER_SUPPORT=OFF \
  -DRDK_BUILD_MOLINTERCHANGE_SUPPORT=OFF \
  -DRDK_BUILD_CHEMDRAW_SUPPORT=OFF \
  -DRDK_BUILD_PUBCHEMSHAPE_SUPPORT=OFF \
  -DRDK_BUILD_DESCRIPTORS3D=OFF \
  -DRDK_BUILD_SLN_SUPPORT=OFF

cmake --build "$BUILD_DIR" -j"$JOBS"
cmake --install "$BUILD_DIR" --component dev

echo "RDKit static libs installed to $INSTALL_DIR (Boost_DIR=$BOOST_CMAKE_DIR)"
